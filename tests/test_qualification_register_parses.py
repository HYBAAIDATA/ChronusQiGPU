"""Release qualification manifest must parse and never self-promote.

This validates metadata integrity only; it does not run or pass the external
release gates, and does not change the human qualification verdict.
"""
from __future__ import annotations

import json
from pathlib import Path

import pytest

from scripts.ci.manifest import _REQUIRED_RELEASE_EVIDENCE

pytestmark = pytest.mark.simulated

APPROVED_MINIMUM_EVIDENCE = (
    "owner-approval.json",
    "device-certificate.json",
    "benchmark.json",
    "sbom.json",
    "provenance.json",
    "rollback-plan.json",
)


def test_production_qualification_register_is_valid_json_and_fail_closed():
    repo_root = Path(__file__).resolve().parents[1]
    with (repo_root / "PRODUCTION_QUALIFIED.json").open(encoding="utf8") as f:
        manifest=json.load(f)
    assert manifest["status"]=="NOT_QUALIFIED"
    assert manifest["external_release_evidence"]["status"]=="MISSING"
    assert manifest["signature"] is None
    evidence=manifest["external_release_evidence"]["required"]
    # The committed register is regenerated by scripts/ci/manifest.py, so it must
    # list exactly the generator's required release evidence (no silent drift).
    assert isinstance(evidence,list) and evidence==list(_REQUIRED_RELEASE_EVIDENCE)
    # Independent floor: the generator may add requirements but not drop these.
    # (reference-vs-device-differential, sustained-soak-and-recovery and
    # pool-acknowledgement were dropped in 53abc10; restoring them is an owner
    # decision, tracked in the PR description.)
    assert set(APPROVED_MINIMUM_EVIDENCE) <= set(evidence)
    assert "owner-approval.json" in evidence
    missing=manifest["external_release_evidence"]["missing"]
    assert set(evidence) <= set(missing)
