"""THESEUS-backed, Ed25519-verified custody for legacy Chronus signed receipts.

AL HARAS owns receipt semantics and signature validation. THESEUS is the only
durable authority. No key material is stored or generated by the custody layer.
A single writer per tenant/stream is required; this is not a distributed
append/consensus service or HSM attestation.
"""
from __future__ import annotations

import hashlib
import json
from dataclasses import fields

from chronus.crypto.signers import Ed25519Signer
from chronus.security.canonical import canonical_bytes
from chronus.security.receipts import Receipt, ReceiptLog, SignedReceipt
from chronus.storage.durable import DurableTheseusService


_EVENT = "AL_HARAS_SIGNED_RECEIPT_V1"
_SCHEMA = "chronus.signed-receipt-custody/1"
_RECEIPT_FIELDS = frozenset(f.name for f in fields(Receipt))


class ReceiptCustodyError(RuntimeError):
    """A signed-receipt stream cannot be independently validated."""


class DurableReceiptLog(ReceiptLog):
    """Persist a signed receipt sequence under a THESEUS tenant and stream.

    Pass a trusted, pinned public key. A new instance reconstructs its chain
    strictly from THESEUS journal events and verifies each signature. Events
    belonging to other streams or authorities are not interpreted as receipts.
    No process-local receipt is evidence of durable custody until committed.
    """

    def __init__(
        self,
        custody: DurableTheseusService,
        tenant_id: str,
        stream_id: str,
        public_key: bytes,
    ) -> None:
        if not isinstance(custody, DurableTheseusService):
            raise TypeError("DurableTheseusService custody is required")
        if not isinstance(tenant_id, str) or not tenant_id.strip():
            raise ValueError("tenant_id is required")
        if not isinstance(stream_id, str) or not stream_id.strip():
            raise ValueError("stream_id is required")
        if not isinstance(public_key, bytes) or len(public_key) != 32:
            raise ValueError("trusted Ed25519 public key must be 32 bytes")
        super().__init__()
        self.custody = custody
        self.tenant_id = tenant_id
        self.stream_id = stream_id
        self.public_key = public_key
        self.public_key_sha256 = hashlib.sha256(public_key).hexdigest()
        self._entries = self._read_verified()

    def _read_verified(self) -> list[SignedReceipt]:
        events = self.custody.get_journal(self.tenant_id)
        if events and not self.custody.verify_journal_continuity(self.tenant_id):
            raise ReceiptCustodyError("THESEUS tenant journal continuity failed")
        recovered: list[SignedReceipt] = []
        previous: str | None = None
        for event in events:
            if event.event_type != _EVENT:
                continue
            try:
                data = json.loads(
                    self.custody.reconstruct(self.tenant_id, event.object_id).decode("utf-8")
                )
                if not isinstance(data, dict) or data.get("schema") != _SCHEMA:
                    raise ValueError("unsupported signed-receipt custody schema")
                if data.get("stream_id") != self.stream_id:
                    continue
                if set(data) != {
                    "schema", "stream_id", "signing_key_sha256",
                    "receipt", "digest", "signature",
                }:
                    raise ValueError("signed-receipt envelope fields invalid")
                if data["signing_key_sha256"] != self.public_key_sha256:
                    raise ValueError("signed-receipt key fingerprint mismatch")
                raw_receipt = data["receipt"]
                if not isinstance(raw_receipt, dict) or set(raw_receipt) != _RECEIPT_FIELDS:
                    raise ValueError("signed-receipt payload fields invalid")
                receipt = Receipt(**raw_receipt)
                if receipt.tenant_id != self.tenant_id:
                    raise ValueError("signed-receipt tenant mismatch")
                digest = data["digest"]
                signature = bytes.fromhex(data["signature"])
                signed = SignedReceipt(receipt, digest, signature)
                if (
                    receipt.sequence != len(recovered)
                    or receipt.prev_digest != previous
                    or not ReceiptLog.verify(signed, self.public_key)
                ):
                    raise ValueError("signed-receipt chain/signature mismatch")
                recovered.append(signed)
                previous = signed.digest
            except (KeyError, TypeError, ValueError, UnicodeError) as exc:
                raise ReceiptCustodyError("invalid stored signed-receipt envelope") from exc
        return recovered

    def append(self, receipt: Receipt, key: Ed25519Signer) -> SignedReceipt:
        if not isinstance(receipt, Receipt) or receipt.tenant_id != self.tenant_id:
            raise ValueError("receipt belongs to a different tenant")
        if not isinstance(key, Ed25519Signer):
            raise TypeError("Ed25519Signer required")
        if key.public_bytes() != self.public_key:
            raise ValueError("signer is not the pinned trusted key")
        # Reject streams that changed since this instance opened. Concurrent
        # multi-writer admission is deliberately not provided by this API.
        recovered = self._read_verified()
        if recovered != self._entries:
            raise ReceiptCustodyError("receipt stream changed; reopen before appending")
        if receipt.sequence != len(recovered) or receipt.prev_digest != self.head_digest:
            raise ValueError("sequence or predecessor mismatch")
        if receipt.key_id != key.key_id:
            raise ValueError("signer key identity mismatch")
        digest = receipt.digest()
        signed = SignedReceipt(receipt, digest, key.sign(bytes.fromhex(digest)))
        if not ReceiptLog.verify(signed, self.public_key):
            raise ReceiptCustodyError("new receipt signature failed independent verification")
        payload = canonical_bytes({
            "schema": _SCHEMA,
            "stream_id": self.stream_id,
            "signing_key_sha256": self.public_key_sha256,
            "receipt": receipt.unsigned(),
            "digest": signed.digest,
            "signature": signed.signature.hex(),
        })
        # This single THESEUS call must complete before local state advances.
        self.custody.append_journal_event(self.tenant_id, _EVENT, payload)
        self._entries.append(signed)
        return signed

    def verify_chain(self, public_key: bytes) -> tuple[bool, str]:
        if public_key != self.public_key:
            return False, "trusted public key mismatch"
        try:
            recovered = self._read_verified()
        except Exception:
            # Any unavailable storage or replay dependency must deny verification.
            return False, "THESEUS receipt custody failed verification"
        if recovered != self._entries:
            return False, "THESEUS receipt stream disagrees with local chain"
        return super().verify_chain(public_key)

    @property
    def evidence_class(self) -> str:
        return "THESEUS_DURABLE_SIGNED_RECEIPT_LOCAL"
