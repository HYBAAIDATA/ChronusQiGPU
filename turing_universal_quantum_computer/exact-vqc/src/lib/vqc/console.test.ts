  assert.match(shots, /\|11⟩/);
  assert.match(console.do("expect 0"), /⟨Z⟩/);
  assert.match(console.do("entropy 0"), /exact integer/);
  assert.match(console.do("product 0 9999"), /SEPARABLE/);
  assert.match(console.do("product 0 1"), /ENTANGLED/);
