"""Metal (MSL) emitter — lowers a KernelSpec onto generated Metal sources.

There is no canonical ``.metal`` source in this tree, so emitted files are
themselves canonical: each carries ``origin="generated"`` and
``verified=False`` — nothing here has been compiled on a Metal device, and
the record says so. Only specs whose precision bound is representable on
Metal lower at all:

- f32 punch-family ops (``poincare_fold``/``poincare_unfold``/``geodesic``/
  ``cnormsq``) map one-to-one onto the canonical kernel bodies;
- ``lucas_pisot_scale`` is u64-exact and Metal ``ulong`` wraps mod 2^64 the
  same way the .cl kernel does — entry name stays byte-identical to the
  canonical kernel's.

Specs requiring f64 (Metal has no device ``double``), i64 helpers the
generator does not cover, or the sha256d family raise
``NoCanonicalKernel`` — an unverifiable guess at a big kernel would be a
fabrication, not a port.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Dict

from hyba.math_ir.specs import get_spec


class NoCanonicalKernel(KeyError):
    """Raised when the MSL generator has no faithful lowering for a spec."""


@dataclass(frozen=True)
class EmittedMetalKernel:
    """One generated MSL source unit for a single spec op."""

    source: str
    entry: str
    spec: str
    canonical_entry: str = ""
    origin: str = "generated"
    verified: bool = False
    notes: Dict[str, Any] = field(default_factory=dict)


_PROLOGUE = """// Generated by hyba.math_ir.emit_msl — canonical MSL source (unverified
// on device; the CPU oracle remains the definition of correctness).
#include <metal_stdlib>
using namespace metal;

constant int DIM = 11;
constant float PHI_F = 1.6180339887498949f;

// w_j = PHI^{-(j+1)} — identical weight sequence to kernels/unified_punch_kernel.cl.
inline float phi_weight(int j) {
    return pown(PHI_F, -(j + 1));
}
"""

_FOLD_BODY = """norm_sq += phi_weight(i) * c * c;"""

_MSL_SOURCES: Dict[str, str] = {
    "poincare_fold": _PROLOGUE
    + """
// 0x08 — x -> x / sqrt(1 + ||x||^2_w). Mirrors kernels/unified_punch_kernel.cl.
kernel void hyba_poincare_fold(
    device const float *x_11d [[buffer(0)]],
    device float *folded [[buffer(1)]],
    constant uint &count [[buffer(2)]],
    uint gid [[thread_position_in_grid]]) {
    if (gid >= count) return;
    float norm_sq = 0.0f;
    for (int i = 0; i < DIM; i++) {
        float c = x_11d[gid * DIM + i];
        FOLD_BODY
    }
    float denom = sqrt(1.0f + norm_sq);
    for (int i = 0; i < DIM; i++)
        folded[gid * DIM + i] = x_11d[gid * DIM + i] / denom;
}
""".replace("FOLD_BODY", _FOLD_BODY.strip()),
    "poincare_unfold": _PROLOGUE
    + """
// 0x09 — inverse fold, clamped below the ball boundary.
kernel void hyba_poincare_unfold(
    device const float *folded [[buffer(0)]],
    device float *x_11d [[buffer(1)]],
    constant uint &count [[buffer(2)]],
    uint gid [[thread_position_in_grid]]) {
    if (gid >= count) return;
    float norm_sq = 0.0f;
    for (int i = 0; i < DIM; i++) {
        float c = folded[gid * DIM + i];
        FOLD_BODY
    }
    float clamped = min(norm_sq, 1.0f - 1e-6f);
    float denom = sqrt(max(1e-6f, 1.0f - clamped));
    for (int i = 0; i < DIM; i++)
        x_11d[gid * DIM + i] = folded[gid * DIM + i] / denom;
}
""".replace("FOLD_BODY", _FOLD_BODY.strip()),
    "geodesic": _PROLOGUE
    + """
// 0x0A — Poincare distance between this item's vector and the wrapped
// neighbour v_idx = (gid + DIM * n_per_punch) % count, as in the .cl kernel.
kernel void hyba_geodesic_distance(
    device const float *vecs [[buffer(0)]],
    device float *distance [[buffer(1)]],
    constant uint &count [[buffer(2)]],
    constant uint &n_per_punch [[buffer(3)]],
    uint gid [[thread_position_in_grid]]) {
    if (gid >= count) return;
    uint v_idx = (gid + DIM * n_per_punch) % count;
    float nu = 0.0f;
    float nv = 0.0f;
    float ds = 0.0f;
    for (int i = 0; i < DIM; i++) {
        float w = phi_weight(i);
        float ui = vecs[gid * DIM + i];
        float vi = vecs[v_idx * DIM + i];
        nu += w * ui * ui;
        nv += w * vi * vi;
        ds += w * (ui - vi) * (ui - vi);
    }
    float denom = (1.0f - nu) * (1.0f - nv);
    distance[gid * DIM] = acosh(1.0f + 2.0f * ds / max(denom, 1e-15f));
}
""",
    "cnormsq": _PROLOGUE
    + """
// 0x15 — weighted squared norm s = sum_j w_j x_j^2.
kernel void hyba_cnormsq(
    device const float *x_11d [[buffer(0)]],
    device float *out [[buffer(1)]],
    constant uint &count [[buffer(2)]],
    uint gid [[thread_position_in_grid]]) {
    if (gid >= count) return;
    float s = 0.0f;
    for (int i = 0; i < DIM; i++) {
        float c = x_11d[gid * DIM + i];
        s += phi_weight(i) * c * c;
    }
    out[gid * DIM] = s;
}
""",
    "lucas_pisot_scale": """// Generated by hyba.math_ir.emit_msl — canonical MSL source (unverified
// on device; the CPU oracle remains the definition of correctness).
// Entry name is byte-identical to
// chronus/mla1517_platform/kernels/mla1517_lucas_pisot_scale.cl.
#include <metal_stdlib>
using namespace metal;

struct mla1517_scale_result { ulong fib; ulong lucas; ulong padovan; };

kernel void mla1517_lucas_pisot_scale(
    device const uint *scales [[buffer(0)]],
    device mla1517_scale_result *out [[buffer(1)]],
    constant uint &count [[buffer(2)]],
    uint gid [[thread_position_in_grid]]) {
    if (gid >= count) return;
    const uint n = scales[gid];
    ulong f0 = 0;
    ulong f1 = 1;
    for (uint i = 0; i < n; ++i) {
        const ulong next = f0 + f1;
        f0 = f1;
        f1 = next;
    }
    ulong p0 = 1;
    ulong p1 = 1;
    ulong p2 = 1;
    for (uint i = 3; i <= n; ++i) {
        const ulong next = p0 + p1;
        p0 = p1;
        p1 = p2;
        p2 = next;
    }
    out[gid].fib = f0;
    out[gid].lucas = (2 * f1) - f0;
    out[gid].padovan = n == 0 ? p0 : (n == 1 ? p1 : p2);
}
""",
}

_MSL_ENTRIES: Dict[str, str] = {
    "poincare_fold": "hyba_poincare_fold",
    "poincare_unfold": "hyba_poincare_unfold",
    "geodesic": "hyba_geodesic_distance",
    "cnormsq": "hyba_cnormsq",
    "lucas_pisot_scale": "mla1517_lucas_pisot_scale",
}


def emit_msl(spec_name: str) -> EmittedMetalKernel:
    """Return the generated MSL source + entry name for ``spec_name``.

    Raises ``NoCanonicalKernel`` where no faithful Metal lowering exists:
    f64-precision specs (Metal devices expose no ``double``), the sha256d
    family, and ops defined only by their CPU oracle.
    """
    spec = get_spec(spec_name)
    if spec.precision_bound == "f64":
        raise NoCanonicalKernel(
            f"{spec.name}: precision_bound 'f64' is not representable in "
            "MSL (Metal devices expose no double) — CPU oracle is authoritative"
        )
    source = _MSL_SOURCES.get(spec.name)
    entry = _MSL_ENTRIES.get(spec.name)
    if source is None or entry is None:
        raise NoCanonicalKernel(
            f"{spec.name}: no MSL lowering — CPU oracle is authoritative"
        )
    return EmittedMetalKernel(
        source=source,
        entry=entry,
        spec=spec.name,
        canonical_entry=spec.entry,
        notes={
            "precision_bound": spec.precision_bound,
            "lucas_dispatch": spec.lucas_dispatch,
        },
    )


__all__ = ["EmittedMetalKernel", "NoCanonicalKernel", "emit_msl"]
