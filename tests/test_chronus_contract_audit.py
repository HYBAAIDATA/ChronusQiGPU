def test_prose_audit_contradictions_are_pinned():
    """The audit request marks these ABSENT; the repository must keep proving
    they exist. If a future change really removes one, this test fails loudly
    and the report must be corrected rather than silently drifting."""
    import hyba_contracts
    import hyba_profiles

    # C2 AssemblyLock: signed, versioned, verified by key.
    assert hasattr(hyba_profiles, "compile_assembly")
    assert hasattr(hyba_profiles, "verify_lock")
    from hyba_profiles.model import AssemblyLock

    names = {f.name for f in AssemblyLock.__dataclass_fields__.values()}
    assert {"schema_version", "policy_hash", "signature"} <= names

    # 12.2 fold modes incl. REHYDRATE, which the audit says has no path.
    from hyba_contracts import FoldMode

    assert {"PRESERVE", "TRANSFORM", "REHYDRATE", "REJECT"} <= {m.name for m in FoldMode}

    # C7 / C8 / 12.12.
    for name in ("ResultReceipt", "EvidenceObject", "AssurancePack", "BackendCertificate"):
        assert hasattr(hyba_contracts, name), name


def test_rehydrate_is_not_a_phantom_contract():
    """The audit's X1 claim rests on 'no rehydration path exists'. Prove the
    path is real: REHYDRATE executes and is counted on the receipt."""
    sys.path.insert(0, str(REPO_ROOT / "scripts"))
    import audit_chronus_contracts as mod
    from hyba_services.folding import FoldExecutor

    regs = mod._fold_contracts()
    ex = FoldExecutor(
        {"audit.fold": regs["audit.fold"]},
        {k: v for k, v in regs.items() if k != "audit.fold"},
        proof=lambda *a, **k: mod._Proof(),
        sign=lambda body: "sig",
    )
    receipt = ex.execute(
        mod._Obj(),
        "audit.fold",
        "rehydrate",
        run_folded=lambda *a: (0.0, 0.0),
        run_exact=lambda *a: 2.0,
    )
    assert receipt.rehydration_count == 1
    assert receipt.mode.name == "REHYDRATE"


def test_reported_artifact_is_valid_json_with_claim_boundaries():
    path = REPO_ROOT / "reports" / "chronus_contract_audit.json"
    if not path.exists():
        return  # generated by the harness run, not required to pre-exist
    data = json.loads(path.read_text(encoding="utf-8"))
    assert data["schema"] == "chronus.contract_audit/v1"
    assert "summary" in data and "status" in data["summary"]
    assert data["spec_present"] is True, "CONTRACTS.md is vendored; record that honestly"
