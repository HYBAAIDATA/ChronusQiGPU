@dataclass
class WorkloadCategory:
    """Workload category with fee percentage."""
    name: str
    description: str
    hermitten_fee_percent: float
    min_gpu_count: int = 0
    max_gpu_count: int = 0


WORKLOAD_CATEGORIES: Dict[str, WorkloadCategory] = {
    "training": WorkloadCategory("training", "AI/ML training workloads", 25.0),
    "inference": WorkloadCategory("inference", "AI/ML inference workloads", 20.0),
    "simulation": WorkloadCategory("simulation", "Scientific simulation workloads", 30.0),
    "mining": WorkloadCategory("mining", "Cryptocurrency mining workloads", 15.0),
    "quantum": WorkloadCategory("quantum", "Quantum computing workloads", 35.0),
    "general": WorkloadCategory("general", "General GPU compute workloads", 25.0),
}


class HermittenBillingService:
    """
    Complete Hermitten billing system with savings-based pricing.
    Charges 25% of GPU memory/workload savings generated.
    Uses in-memory storage for demo; production uses PostgreSQL.
    """

    DEFAULT_FEE_PERCENT = 25.0

    def __init__(self, hermitten_fee_percent: float = None):
        self.hermitten_fee_percent = hermitten_fee_percent or self.DEFAULT_FEE_PERCENT
        self._baselines: Dict[str, Dict[str, Any]] = {}
        self._compressed_usages: Dict[str, List[Dict[str, Any]]] = {}
        self._bills: Dict[str, HermittenBill] = {}
        self._savings_history: List[Dict[str, Any]] = []

    def calculate_savings(self, baseline: Dict[str, Any],
                          compressed: Dict[str, Any]) -> WorkloadSavings:
        """Calculate savings from phi-compression."""
        gpu_savings_count = baseline["gpu_count"] - compressed["gpu_count"]
        gpu_savings_percent = (gpu_savings_count / baseline["gpu_count"]) * 100 if baseline["gpu_count"] > 0 else 0

        memory_savings_gb = baseline["memory_gb"] - compressed["memory_gb"]
        memory_savings_percent = (memory_savings_gb / baseline["memory_gb"]) * 100 if baseline["memory_gb"] > 0 else 0

        baseline_cost = baseline["cost_per_month"]
        compressed_cost = compressed["cost_per_month"]
        cost_savings = baseline_cost - compressed_cost
        cost_savings_percent = (cost_savings / baseline_cost) * 100 if baseline_cost > 0 else 0

        # Determine fee percent from workload type
        workload_type = compressed.get("workload_type", "general")
        category = WORKLOAD_CATEGORIES.get(workload_type, WORKLOAD_CATEGORIES["general"])
        fee_percent = category.hermitten_fee_percent

        hermitten_fee = round(cost_savings * (fee_percent / 100), 2)
        customer_net = round(cost_savings - hermitten_fee, 2)
        customer_net_percent = (customer_net / baseline_cost) * 100 if baseline_cost > 0 else 0

        return WorkloadSavings(
            original_gpu_count=baseline["gpu_count"],
            original_memory_gb=baseline["memory_gb"],
            original_cost=baseline_cost,
            compressed_gpu_count=compressed["gpu_count"],
            compressed_memory_gb=compressed["memory_gb"],
            compressed_cost=compressed_cost,
            gpu_savings_count=gpu_savings_count,
            gpu_savings_percent=gpu_savings_percent,
            memory_savings_gb=memory_savings_gb,
            memory_savings_percent=memory_savings_percent,
            cost_savings=round(cost_savings, 2),
            cost_savings_percent=cost_savings_percent,
            hermitten_fee_percent=fee_percent,
            hermitten_fee_amount=hermitten_fee,
            customer_net_savings=customer_net,
            customer_net_percent=customer_net_percent,
            compression_ratio=compressed.get("compression_ratio", 0),
            phi_power_used=compressed.get("phi_power", 12),
            fold_depth=compressed.get("fold_depth", 8),
        )

    def create_baseline(self, user_id: str, baseline_data: Dict[str, Any]) -> Dict[str, Any]:
        """Create a GPU baseline for a customer."""
        baseline_id = str(uuid.uuid4())
        now = time.time()
        period_days = baseline_data.get("measurement_period_days", 30)

        baseline = {
            "id": baseline_id,
            "tenant_id": user_id,
            "user_id": user_id,
            "baseline_name": baseline_data.get("name", "default"),
            "gpu_model": baseline_data["gpu_model"],
            "gpu_count": baseline_data["gpu_count"],
            "memory_gb": baseline_data["memory_gb"],
            "memory_bandwidth_gbps": baseline_data.get("memory_bandwidth_gbps", 0),
            "compute_tflops": baseline_data.get("compute_tflops", 0),
            "power_watts": baseline_data.get("power_watts", 0),
            "cost_per_hour": baseline_data["cost_per_hour"],
            "cost_per_month": baseline_data["cost_per_month"],
            "workload_type": baseline_data.get("workload_type", "general"),
            "workload_description": baseline_data.get("description", ""),
            "measurement_period_days": period_days,
            "baseline_start": now,
            "baseline_end": now + period_days * 86400,
            "is_active": True,
            "created_at": now,
            "updated_at": now,
        }
        self._baselines[baseline_id] = baseline

        return {
            "baseline_id": baseline_id,
            "status": "created",
            "name": baseline["baseline_name"],
            "gpu_model": baseline["gpu_model"],
            "gpu_count": baseline["gpu_count"],
            "memory_gb": baseline["memory_gb"],
            "cost_per_month": baseline["cost_per_month"],
        }

    def get_baseline(self, user_id: str) -> Optional[Dict[str, Any]]:
        """Get active baseline for user."""
        for b in self._baselines.values():
            if b["user_id"] == user_id and b["is_active"]:
                return b
        return None

    def record_compressed_usage(self, user_id: str, baseline_id: str,
                                compressed_data: Dict[str, Any]) -> Dict[str, Any]:
        """Record actual compressed usage."""
        baseline = self._baselines.get(baseline_id)
        if not baseline:
            return {"error": "Baseline not found"}

        usage_id = str(uuid.uuid4())
        now = time.time()
        period_days = baseline.get("measurement_period_days", 30)

        memory_saved_gb = baseline["memory_gb"] - compressed_data["memory_gb"]
        memory_saved_percent = (memory_saved_gb / baseline["memory_gb"]) * 100 if baseline["memory_gb"] > 0 else 0

        cost_saved = baseline["cost_per_month"] - compressed_data["cost_per_month"]
        cost_saved_percent = (cost_saved / baseline["cost_per_month"]) * 100 if baseline["cost_per_month"] > 0 else 0

        usage = {
            "id": usage_id,
            "tenant_id": user_id,
            "user_id": user_id,
            "baseline_id": baseline_id,
            "gpu_model": compressed_data["gpu_model"],
            "gpu_count": compressed_data["gpu_count"],
            "memory_gb": compressed_data["memory_gb"],
            "memory_saved_gb": round(memory_saved_gb, 2),
            "memory_saved_percent": round(memory_saved_percent, 2),
            "cost_saved": round(cost_saved, 2),
            "cost_saved_percent": round(cost_saved_percent, 2),
            "phi_power_used": compressed_data.get("phi_power", 12),
            "fold_depth": compressed_data.get("fold_depth", 8),
            "compression_ratio": compressed_data.get("compression_ratio", 0),
            "reconstruction_error": compressed_data.get("reconstruction_error", 0),
            "workload_type": compressed_data.get("workload_type", "general"),
            "measurement_start": now - period_days * 86400,
            "measurement_end": now,
            "is_billable": True,
            "created_at": now,
        }

        if user_id not in self._compressed_usages:
            self._compressed_usages[user_id] = []
        self._compressed_usages[user_id].append(usage)

        return {
            "usage_id": usage_id,
            "memory_saved_gb": round(memory_saved_gb, 2),
            "memory_saved_percent": round(memory_saved_percent, 2),
            "cost_saved": round(cost_saved, 2),
            "cost_saved_percent": round(cost_saved_percent, 2),
        }

    def generate_hermitten_bill(self, user_id: str,
                                period_start: float = None,
                                period_end: float = None) -> Dict[str, Any]:
        """Generate a Hermitten bill for a customer."""
        baseline = self.get_baseline(user_id)
        if not baseline:
            return {"error": "No active baseline found"}

        now = time.time()
        if period_start is None:
            period_start = now - 30 * 86400
        if period_end is None:
            period_end = now

        usages = self._compressed_usages.get(user_id, [])

        total_original_gpu = baseline["gpu_count"]
        total_original_memory = baseline["memory_gb"]
        total_original_cost = baseline["cost_per_month"]

        if usages:
            avg_compressed_gpu = sum(u["gpu_count"] for u in usages) // len(usages)
            avg_compressed_memory = sum(u["memory_gb"] for u in usages) / len(usages)
            avg_compressed_cost = total_original_cost - sum(u["cost_saved"] for u in usages) / len(usages)
        else:
            avg_compressed_gpu = total_original_gpu
            avg_compressed_memory = total_original_memory
            avg_compressed_cost = total_original_cost

        gpu_savings = total_original_gpu - avg_compressed_gpu
        gpu_savings_pct = (gpu_savings / total_original_gpu) * 100 if total_original_gpu > 0 else 0
        memory_savings = total_original_memory - avg_compressed_memory
        memory_savings_pct = (memory_savings / total_original_memory) * 100 if total_original_memory > 0 else 0
        cost_savings = total_original_cost - avg_compressed_cost
        cost_savings_pct = (cost_savings / total_original_cost) * 100 if total_original_cost > 0 else 0

        workload_type = baseline.get("workload_type", "general")
        category = WORKLOAD_CATEGORIES.get(workload_type, WORKLOAD_CATEGORIES["general"])
        fee_percent = category.hermitten_fee_percent

        hermitten_fee = round(cost_savings * (fee_percent / 100), 2)
        customer_net = round(cost_savings - hermitten_fee, 2)
        customer_net_pct = (customer_net / total_original_cost) * 100 if total_original_cost > 0 else 0

        bill_id = str(uuid.uuid4())
        bill = HermittenBill(
            id=bill_id,
            user_id=user_id,
            tenant_id=user_id,
            billing_period_start=period_start,
            billing_period_end=period_end,
            baseline_gpu_count=total_original_gpu,
            baseline_memory_gb=total_original_memory,
            baseline_cost=total_original_cost,
            compressed_gpu_count=avg_compressed_gpu,
            compressed_memory_gb=round(avg_compressed_memory, 2),
            compressed_cost=round(avg_compressed_cost, 2),
            gpu_savings_count=gpu_savings,
            gpu_savings_percent=round(gpu_savings_pct, 2),
            memory_savings_gb=round(memory_savings, 2),
            memory_savings_percent=round(memory_savings_pct, 2),
            cost_savings=round(cost_savings, 2),
            cost_savings_percent=round(cost_savings_pct, 2),
            hermitten_fee_percent=fee_percent,
            hermitten_fee_amount=hermitten_fee,
            customer_net_savings=customer_net,
            customer_net_percent=round(customer_net_pct, 2),
            total_original_cost=total_original_cost,
            total_compressed_cost=round(avg_compressed_cost, 2),
            total_savings=round(cost_savings, 2),
            total_hermitten_fee=hermitten_fee,
            total_customer_benefit=customer_net,
            status="draft",
            payment_status="pending",
            created_at=now,
        )
        self._bills[bill_id] = bill

        # Record savings history
        self._savings_history.append({
            "user_id": user_id,
            "billing_id": bill_id,
            "period_start": period_start,
            "period_end": period_end,
            "baseline_cost": total_original_cost,
            "compressed_cost": round(avg_compressed_cost, 2),
            "savings_amount": round(cost_savings, 2),
            "savings_percent": round(cost_savings_pct, 2),
            "hermitten_fee": hermitten_fee,
            "customer_savings": customer_net,
            "compression_ratio_avg": usages[0]["compression_ratio"] if usages else 0,
            "created_at": now,
        })

        return bill.to_dict()

    def get_hermitten_summary(self, user_id: str) -> Dict[str, Any]:
        """Get Hermitten billing summary for a customer."""
        user_bills = [b for b in self._bills.values() if b.user_id == user_id and b.status != "voided"]

        if not user_bills:
            return {
                "total_bills": 0,
                "total_savings": 0,
                "total_hermitten_fee": 0,
                "total_customer_benefit": 0,
                "avg_savings_percent": 0,
                "avg_memory_savings_percent": 0,
            }

        return {
            "total_bills": len(user_bills),
            "total_savings": round(sum(b.total_savings for b in user_bills), 2),
            "total_hermitten_fee": round(sum(b.total_hermitten_fee for b in user_bills), 2),
            "total_customer_benefit": round(sum(b.total_customer_benefit for b in user_bills), 2),
            "avg_savings_percent": round(sum(b.cost_savings_percent for b in user_bills) / len(user_bills), 2),
            "avg_memory_savings_percent": round(sum(b.memory_savings_percent for b in user_bills) / len(user_bills), 2),
        }

    def get_savings_projections(self, user_id: str) -> Dict[str, Any]:
        """Get savings projections based on current usage."""
        baseline = self.get_baseline(user_id)
        if not baseline:
            return {"error": "No active baseline found"}

        usages = self._compressed_usages.get(user_id, [])
        if usages:
            avg_memory_savings = sum(u["memory_saved_percent"] for u in usages) / len(usages)
            avg_cost_savings = sum(u["cost_saved_percent"] for u in usages) / len(usages)
            avg_compression_ratio = sum(u["compression_ratio"] for u in usages) / len(usages)
            avg_phi_power = sum(u["phi_power_used"] for u in usages) / len(usages)
        else:
            avg_memory_savings = 0
            avg_cost_savings = 0
            avg_compression_ratio = 0
            avg_phi_power = 0

        monthly_cost = baseline["cost_per_month"]
        projected_savings = round(monthly_cost * (avg_cost_savings / 100), 2) if avg_cost_savings > 0 else 0

        workload_type = baseline.get("workload_type", "general")
        category = WORKLOAD_CATEGORIES.get(workload_type, WORKLOAD_CATEGORIES["general"])
        fee_percent = category.hermitten_fee_percent

        projected_hermitten_fee = round(projected_savings * (fee_percent / 100), 2)
        projected_net = round(projected_savings - projected_hermitten_fee, 2)

        return {
            "current_baseline": {
                "gpu_model": baseline["gpu_model"],
                "gpu_count": baseline["gpu_count"],
                "memory_gb": baseline["memory_gb"],
                "monthly_cost": baseline["cost_per_month"],
            },
            "current_compression": {
                "avg_memory_savings_percent": round(avg_memory_savings, 2),
                "avg_cost_savings_percent": round(avg_cost_savings, 2),
                "avg_compression_ratio": round(avg_compression_ratio, 2),
                "avg_phi_power": avg_phi_power,
            },
            "projections": {
                "monthly_savings": projected_savings,
                "hermitten_fee": projected_hermitten_fee,
                "customer_net_savings": projected_net,
                "annual_savings": round(projected_savings * 12, 2),
                "annual_customer_benefit": round(projected_net * 12, 2),
            },
        }

    def get_bills(self, user_id: str, limit: int = 12) -> List[Dict[str, Any]]:
        """Get bills for a customer."""
        user_bills = [b for b in self._bills.values() if b.user_id == user_id]
        user_bills.sort(key=lambda b: b.billing_period_start, reverse=True)
        return [b.to_dict() for b in user_bills[:limit]]

    def get_bill(self, bill_id: str) -> Optional[Dict[str, Any]]:
        """Get a specific bill."""
        bill = self._bills.get(bill_id)
        return bill.to_dict() if bill else None

    def get_workload_categories(self) -> Dict[str, Any]:
        """Get all workload categories."""
        return {
            name: {
                "description": cat.description,
                "hermitten_fee_percent": cat.hermitten_fee_percent,
            }
            for name, cat in WORKLOAD_CATEGORIES.items()
        }
