"""Tests for the iGPU contract audit harness.

The harness is only worth running if it can fail. These tests prove it is
fail-closed: a broken invariant must produce a non-zero exit, and the
contradictions between the prose audit and this repository must stay
pinned so they cannot silently regress.
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

HARNESS = REPO_ROOT / "scripts" / "audit_chronus_contracts.py"


def _run(*args, env=None):
    return subprocess.run(
        [sys.executable, str(HARNESS), *args],
        cwd=str(REPO_ROOT),
        env=env,
        capture_output=True,
        text=True,
    )


def test_harness_exists_and_passes_on_intact_code():
    proc = _run("--only", "spec,C2,12.2,12.2b,receipts,assurance,governance,seam")
    assert proc.returncode == 0, proc.stdout[-3000:]
    assert "STATUS            : OK" in proc.stdout


def test_harness_exits_nonzero_when_an_invariant_is_broken(tmp_path):
    """Sabotage the lock check; the run must fail by name, not just exit != 0."""
    (tmp_path / "sitecustomize.py").write_text(
        "import hyba_profiles as hp\n"
        "_real = hp.verify_lock\n"
        "def _fake(result, signing_key):\n"
        "    return True  # a lock now verifies under ANY key\n"
        "hp.verify_lock = _fake\n",
        encoding="utf-8",
    )
    env = dict(os.environ)
    env["PYTHONPATH"] = f"{tmp_path}{os.pathsep}{REPO_ROOT}"
    proc = _run("--only", "C2", env=env)
    assert proc.returncode == 1, f"expected exit 1, got {proc.returncode}\n{proc.stdout[-2000:]}"
    assert "STATUS            : FAIL" in proc.stdout
    assert "foreign key" in proc.stdout
    assert "STATUS            : OK" not in proc.stdout


def test_harness_fails_closed_on_an_unknown_section():
    proc = _run("--only", "not-a-section")
    assert proc.returncode != 0
    assert "unknown section" in (proc.stderr + proc.stdout)


